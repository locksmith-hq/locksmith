#!/usr/bin/env bash
# Cheap "is there anything to do?" check so idle worker runs exit in seconds (idle agents spend nothing).
# Exit 0 and print the reasons when there is work; exit 1 and print "idle" when there is none.
set -uo pipefail
repo=locksmith-hq/locksmith
owner="${OWNER_LOGIN:-tomer555}"
work=()
git fetch -q origin 2>/dev/null

# Finished PRs waiting for the merge queue
n=$(gh api "repos/$repo/issues?labels=ready-to-merge&state=open" -q length)
[ "$n" -gt 0 ] && work+=("$n ready-to-merge PR(s)")

# Red main CI
c=$(gh api "repos/$repo/actions/workflows/ci.yml/runs?branch=main&per_page=1" -q '.workflow_runs[0].conclusion // ""')
[ "$c" = failure ] && work+=("main CI is red")

# Owner replied on a needs-owner issue (latest comment by the owner that no agent wrote)
for i in $(gh api "repos/$repo/issues?labels=needs-owner&state=open" -q '.[].number'); do
  last=$(gh api "repos/$repo/issues/$i/comments?per_page=100" -q '[.[]]|last|select(.!=null)|[.user.login, .body]|@json')
  [ -n "$last" ] || continue
  who=$(jq -r '.[0]' <<<"$last"); body=$(jq -r '.[1]' <<<"$last")
  if [ "$who" = "$owner" ] && ! grep -qE '<!-- agent -->|Generated by \[Claude Code\]|run-metadata' <<<"$body"; then
    work+=("owner replied on #$i")
  fi
done

# An open change whose next unchecked task is not an owner gate
for d in openspec/changes/*/; do
  id=$(basename "$d"); [ "$id" = archive ] && continue
  f="$d/tasks.md"; [ -f "$f" ] || continue
  t=$(git show "origin/claude/change-$id:$f" 2>/dev/null || cat "$f")
  next=$(grep -m1 -E '^\s*- \[ \]' <<<"$t" || true)
  # Finished on main but never archived (its PR skipped the archive step).
  if [ -z "$next" ]; then grep -qE '^\s*- \[ \]' "$f" || work+=("$id is finished but not archived"); continue; fi
  if grep -qiE 'owner (reviews|gate|decision)' <<<"$next"; then continue; fi
  work+=("$id has open tasks")
done

if [ "${#work[@]}" -gt 0 ]; then printf 'work: %s\n' "${work[@]}"; exit 0; fi
echo idle; exit 1
