#!/usr/bin/env bash
# Local CI attestation while the `ci` workflow is disabled (owner-only file; #307).
#   scripts/local-ci-attest.sh <pr-number>
# Runs every check the `ci` workflow runs (just ci, the hygiene extras, gitleaks, cargo-deny,
# desktop fmt) on a clean checkout of the PR head, then comments "local-ci <sha>: PASS" on the PR.
# merge-gate.sh gate 4 accepts that comment for the exact head SHA only while `ci` is not active.
# Run it before adding ready-to-merge, and again after every push.
set -uo pipefail
repo=locksmith-hq/locksmith
n="${1:?usage: local-ci-attest.sh <pr-number>}"
die() { echo "local-ci FAIL $*"; exit 1; }

sha=$(gh api "repos/$repo/pulls/$n" -q .head.sha) || die "cannot read PR #$n"
[ "$(git rev-parse HEAD)" = "$sha" ] || die "HEAD $(git rev-parse --short HEAD) is not the PR head ${sha:0:7}; push first"
[ -z "$(git status --porcelain)" ] || die "working tree is not clean"
branch=$(git rev-parse --abbrev-ref HEAD)

steps=(
  "just ci"
  "bash scripts/check-agent-docs.sh"
  "gitleaks git --no-banner --redact --exit-code 1 ."
  "cargo deny check"
  "cargo fmt --manifest-path apps/desktop/src-tauri/Cargo.toml --check"
)
start=$(date +%s)
for s in "${steps[@]}"; do
  echo "== $s"
  BRANCH="$branch" bash -c "$s" || die "$s"
done
[ "$(git rev-parse HEAD)" = "$sha" ] && [ -z "$(git status --porcelain)" ] || die "tree changed during the run"
dur=$(( $(date +%s) - start ))

body=$(printf '<!-- agent -->\nlocal-ci %s: PASS\n\nThe `ci` workflow is disabled, so these ran in the agent VM on a clean checkout of %s (%ss):\n%s\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n' \
  "$sha" "${sha:0:7}" "$dur" "$(printf -- '- `%s`\n' "${steps[@]}")")
gh api "repos/$repo/issues/$n/comments" -f body="$body" -q .html_url >/dev/null || die "cannot post comment"
echo "local-ci PASS $sha"
