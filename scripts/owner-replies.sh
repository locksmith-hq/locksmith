#!/usr/bin/env bash
# Open needs-owner issues whose latest comment is the owner's own (not agent-written): the lead
# answers each one (docs/agents/lead.md step 0). Prints one issue number per line.
set -uo pipefail
repo=locksmith-hq/locksmith
owner="${OWNER_LOGIN:-tomer555}"
for i in $(gh api "repos/$repo/issues?labels=needs-owner&state=open" -q '.[].number'); do
  last=$(gh api "repos/$repo/issues/$i/comments?per_page=100" -q '[.[]]|last|select(.!=null)|[.user.login, .body]|@json')
  [ -n "$last" ] || continue
  who=$(jq -r '.[0]' <<<"$last"); body=$(jq -r '.[1]' <<<"$last")
  if [ "$who" = "$owner" ] && ! grep -qE '<!-- agent -->|Generated by \[Claude Code\]|run-metadata' <<<"$body"; then
    echo "$i"
  fi
done
