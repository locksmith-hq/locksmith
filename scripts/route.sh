#!/usr/bin/env bash
# Routes help between agent roles as configured in docs/agents/routing.json (owner-only; both are guarded).
#   route.sh event <event.json>    roles to wake for a GitHub event, "role<TAB>reason" per line (wake-agents.yml)
#   route.sh debate <issue>        debate guard: "wake <role> <why>" or "wait <why>"; agents act only on their own wake
#   route.sh fire <role> <reason>  wake a role's routine; its token comes from the env var routing.json names
#   route.sh tick                  fire each batched (Opus) role once for its queue (wake-agents.yml, every 2 h)
#   route.sh selftest
# Roles come from GitHub logins, so an agent cannot speak for another role or skip the cap. Shortcut: while
# identities are paused (#299) agents post as the owner and a role marker decides; drop it once they are live.
set -uo pipefail
# shellcheck disable=SC2016  # jq programs use $vars
repo=locksmith-hq/locksmith
here=$(cd "$(dirname "$0")" && pwd)
cfg="${ROUTING:-$here/../docs/agents/routing.json}"
marker='<!-- agent -->|Generated by \[Claude Code\]|run-metadata'

# Debate decision from {state, labels, opener, opener_body, comments:[{login, body}]} on stdin.
decide() {
  jq -r --slurpfile c "$cfg" '
    $c[0] as $cfg | $cfg.channels.debate as $ch | $ch.escalate_to as $esc | $ch.turns as $cap |
    def marked($b): ($b // "") | test("<!-- agent|Generated by \\[Claude Code\\]|run-metadata");
    # A bot login is its role. While identities are paused agents post as the owner: then a marked post
    # names its role with "<!-- role: pm -->"; an unmarked owner-login post is the owner.
    def role($l; $b):
      ([$cfg.roles|to_entries[]|select(.key != "owner" and (.value.logins|index($l)))|.key][0]) as $bot |
      if $bot then $bot
      elif ($cfg.roles.owner.logins|index($l)) then
        if marked($b) then ((($b // "")|capture("<!-- role: (?<r>[a-z]+) -->")?|.r) // "other") else "owner" end
      else "other" end;
    def stance($b): ((($b // "")|ascii_downcase|capture("(?m)^\\s*stance:\\s*(?<s>agree|counter|hold)")?|.s) // "counter");
    def other($r): ($ch.between - [$r])[0];
    ([{login: .opener, body: .opener_body}] + .comments | map({role: role(.login; .body), stance: stance(.body)})) as $all |
    # Walk the turns: they alternate (a second post in a row does not count) and the first agree, hold or
    # exhausted cap ends the debate. Once ended, only the escalate_to role acting on it matters.
    (reduce ($all[]|select(.role as $r|$ch.between|index($r))) as $t ({turns: [], end: null, by: null, after: false};
      if .end then (if $t.role == $esc then .after = true else . end)
      elif (.turns|length) > 0 and .turns[-1].role == $t.role then .
      else .turns += [$t] |
        if ($t.stance == "agree" or $t.stance == "hold") then .end = $t.stance | .by = $t.role
        elif ([.turns[]|select(.role == other($t.role))]|length) >= $cap then .end = "cap" | .by = $t.role
        else . end
      end)) as $d |
    if .state == "closed" then "wait closed"
    elif (.labels|index("needs-owner")) then "wait with the owner"
    elif ($all|length) > 0 and $all[-1].role == "owner" then "wake \($esc) owner commented"
    elif ($d.turns|length) == 0 then "wait no debate turns yet"
    elif $d.end then
      if $d.after or $d.by == $esc then "wait \($esc) settles it"
      elif $d.end == "agree" then "wake \($esc) \($d.by) agreed: record it and close"
      elif $d.end == "hold" then "wake \($esc) \($d.by) agreed to disagree: escalate to the owner"
      else "wake \($esc) turn cap \($cap) reached: escalate to the owner" end
    else other($d.turns[-1].role) as $next |
      "wake \($next) turn \([$d.turns[]|select(.role == $next)]|length + 1) of \($cap)\(if ([$d.turns[]|select(.role == $next)]|length + 1) == $cap then ", the last" else "" end)"
    end'
}

debate_input() { # <issue>: the decide() input, from GitHub (or $DEBATE_JSON in the selftest)
  if [ -n "${DEBATE_JSON:-}" ]; then cat "$DEBATE_JSON"; return; fi
  jq -n --argjson i "$(gh api "repos/$repo/issues/$1")" --argjson c "$(gh api --paginate "repos/$repo/issues/$1/comments?per_page=100" | jq -s add)" \
    '{state: $i.state, labels: [$i.labels[].name], opener: $i.user.login, opener_body: $i.body, comments: [$c[]|{login: .user.login, body: .body}]}'
}

cfgq() { jq -r "$@" "$cfg"; }

# True when another owner reply on the issue came under 60 s before this one: its wake already covers
# this one (#397: "C" then "Approved C" 13 s apart fired two lead runs that did the same work).
replied_just_before() { # <issue> <comment-id> <created_at>; comments from GitHub or $COMMENTS_JSON
  [ -n "$3" ] || return 1
  { if [ -n "${COMMENTS_JSON:-}" ]; then cat "$COMMENTS_JSON"; else gh api --paginate "repos/$repo/issues/$1/comments?per_page=100" | jq -s add; fi; } |
    jq -e --argjson id "$2" --arg t "$3" --argjson o "$(cfgq -c .roles.owner.logins)" --arg m "$marker" '
      ($t|fromdateiso8601) as $now | any(.[]; .id != $id and (.user.login as $l | $o | index($l)) and ((.body // "") | test($m) | not)
        and (($now - (.created_at|fromdateiso8601)) as $d | ($d > 0 or ($d == 0 and .id < $id)) and $d < 60))' >/dev/null 2>&1
}

role_of() { # <login>: the agent role whose logins include it, else nothing (the owner is not a role here)
  cfgq --arg l "$1" '[.roles|to_entries[]|select(.key != "owner" and (.value.logins // []|index($l)))|.key][0] // empty'
}

# "raiser" means the role named by "<!-- raised-by: <role> -->" in the issue body, else the role of the
# issue's author (a worker's needs-rescue), else the lead. A marker that names no routine (`worker`,
# `optimizer`) is ignored: it used to crash fire() and drop the wake (#563).
resolve() { # <role or "raiser"> <event.json>
  [ "$1" = raiser ] || { printf '%s' "$1"; return; }
  local r; r=$(jq -r '(.issue.body // "") | (capture("<!-- raised-by: (?<r>[a-z-]+) -->")?|.r) // empty' "$2")
  [ -n "$r" ] && [ -z "$(cfgq --arg r "$r" '.roles[$r].trigger // empty')" ] && r=
  [ -n "$r" ] || r=$(role_of "$(jq -r '.issue.user.login // ""' "$2")")
  printf '%s' "${r:-lead}"
}

# Each PR belongs to its author: the worker or lead whose App opened PR <n>, else default_worker (owner or unknown author).
pr_worker() { # <pr number>; the author from GitHub (or $PR_AUTHOR in the selftest)
  local who r; who=${PR_AUTHOR:-$( [ -n "$1" ] && gh api "repos/$repo/pulls/$1" -q .user.login 2>/dev/null)}
  r=$(role_of "$who"); case "$r" in worker-*|lead) printf '%s' "$r" ;; *) cfgq .default_worker ;; esac
}

event() { # <event.json>; GITHUB_EVENT_NAME says which event it is
  local ev=$1 n labels l to who body
  case "${GITHUB_EVENT_NAME:?}" in
    workflow_run)
      local wf concl br trig pr
      read -r wf concl br trig pr < <(jq -r '.workflow_run|[.name, .conclusion, .head_branch, .event, (.pull_requests[0].number // "")]|@tsv' "$ev")
      if [ "$wf" = ci ] && [ "$concl" = failure ]; then
        if [ "$br" = main ]; then printf '%s\tCI failed on main\n' lead
        elif [ "$trig" = pull_request ] && [[ "$br" == claude/* ]]; then printf '%s\tCI failed on PR #%s (%s)\n' "$(pr_worker "$pr")" "${pr:-?}" "$br"; fi
      elif [ "$wf" = claude-review ] && [ "$trig" = pull_request ] && [ -n "$pr" ] && [ "$concl" = failure ]; then
        printf '%s\tmerge review failed on PR #%s\n' "$(pr_worker "$pr")" "$pr"
      fi ;;
    issues)
      n=$(jq -r .issue.number "$ev"); labels=$(jq -r '.issue.labels[].name' "$ev")
      case "$(jq -r .action "$ev")" in
        labeled)
          l=$(jq -r .label.name "$ev")
          if [ "$l" = debate ]; then debate_input "$n" | decide | awk -v n="$n" '$1=="wake"{r=$2; sub(/^wake [a-z]+ /,""); print r "\tdebate #" n ": " $0}'
          else to=$(cfgq --arg l "$l" '. as $c|$c.channels[$l].to // empty|select($c.roles[.]|has("trigger"))'); [ -n "$to" ] && printf '%s\t%s #%s opened\n' "$to" "$l" "$n"; fi ;;
        closed)
          for l in $labels; do
            to=$(resolve "$(cfgq --arg l "$l" '.channels[$l].on_close // empty')" "$ev"); [ -n "$to" ] && printf '%s\t%s #%s closed\n' "$to" "$l" "$n"
          done ;;
      esac ;;
    issue_comment)
      n=$(jq -r .issue.number "$ev"); labels=$(jq -r '.issue.labels[].name' "$ev")
      who=$(jq -r .comment.user.login "$ev"); body=$(jq -r .comment.body "$ev")
      id=$(jq -r '.comment.id // 0' "$ev"); at=$(jq -r '.comment.created_at // ""' "$ev")
      owner=false; cfgq '.roles.owner.logins[]' | grep -qxF "$who" && ! grep -qE "$marker" <<<"$body" && owner=true
      # Owner tags (@locksmith-lead or the org team @locksmith-hq/lead, ...) wake exactly the tagged roles, on issues and PRs alike, and replace the reply rule.
      # The research bot (open internet, comments only) tags the roles its answer is for; it never wakes itself.
      src=owner; [ "$owner" = false ] && [ "$(role_of "$who")" = research ] && src=research
      tags=$({ [ "$owner" = true ] || [ "$src" = research ]; } && grep -oE '@locksmith-(hq/)?[a-z]+' <<<"$body" | sort -u | while read -r t; do cfgq --arg t "$t" '.mentions[$t] // empty'; done | grep -vx "$([ "$src" = research ] && echo research)")
      if [ -n "$tags" ]; then
        for to in $tags; do printf '%s\t%s tagged you on #%s: %s\n' "$to" "$src" "$n" "$(jq -r '.comment.html_url // ""' "$ev")"; done
        return 0
      fi
      [ "$src" = research ] && return 0
      [ "$(jq -r '.issue.pull_request != null' "$ev")" = true ] && return 0
      for l in $labels; do
        to=$(resolve "$(cfgq --arg l "$l" '.channels[$l].on_reply // empty')" "$ev")
        if [ -n "$to" ] && [ "$owner" = true ] && ! replied_just_before "$n" "$id" "$at"; then
          printf '%s\towner replied on %s #%s\n' "$to" "$l" "$n"
        fi
        [ "$l" = debate ] && debate_input "$n" | decide | awk -v n="$n" '$1=="wake"{r=$2; sub(/^wake [a-z]+ /,""); print r "\tdebate #" n ": " $0}'
      done ;;
  esac | awk -F'\t' '!seen[$1]++'  # one wake per role per event
}

# Batched roles (routing.json `batched`: the Opus routines; owner 2026-11-22: 29 Opus lead runs in 24 h, mostly for
# nothing) wake at once only when the owner tags them. Any other wake labels the issue or PR `wake-<role>`; `tick`
# (wake-agents.yml, every 2 h) fires each role once for everything labelled, then clears those labels.
batched() { [ "$(cfgq --arg r "$1" '.roles[$r].batched // false')" = true ]; }
now_ok() { [[ "$1" == "owner tagged you"* || "$1" == queue:* ]]; }

queue_add() { # <role> <reason>: label the issue or PR the reason names; main's state needs no label (tick reads it)
  local n; n=$(grep -oE '#[0-9]+' <<<"$2" | head -1 | tr -d '#')
  if [ -n "$n" ] && [ -z "${ROUTE_DRYRUN:-}" ]; then gh api "repos/$repo/issues/$n/labels" -f "labels[]=wake-$1" >/dev/null || return 1; fi
  echo "queued for $1${n:+ on #$n}: $2"
}

queue_of() { # <role>: one item per line; from GitHub or $QUEUE_JSON {"items": [...], "main": {...}} in the selftest
  local st; st=${QUEUE_JSON:+$(cat "$QUEUE_JSON")}
  [ -n "$st" ] || st=$(jq -n --argjson i "$(gh api "repos/$repo/issues?labels=wake-$1&state=all&per_page=100" -q '[.[]|{number, labels: [.labels[].name]}]')" \
    --argjson m "$(gh api "repos/$repo/actions/workflows/ci.yml/runs?branch=main&status=completed&per_page=1" -q '.workflow_runs[0]|{conclusion, updated_at}')" '{items: $i, main: $m}')
  jq -r --arg r "$1" --arg now "${NOW:-$(date -u +%Y-%m-%dT%H:%M:%SZ)}" '
    (.items[]|"#\(.number) (\([.labels[]|select(startswith("wake-")|not)]|join(", ")))"),
    (select($r == "lead")|.main // {}|select(.conclusion == "failure" and (($now|fromdateiso8601) - (.updated_at|fromdateiso8601)) > 7200)|"main red over 2 h")' <<<"$st"
}

tick() { # fire each batched role once for its queue, then clear the labels it was fired for
  local r q n code
  for r in $(cfgq '.roles|to_entries[]|select(.value.batched == true)|.key'); do
    q=$(queue_of "$r"); [ -n "$q" ] || { echo "$r: queue empty"; continue; }
    code=$(fire "$r" "queue: $(paste -sd ';' - <<<"$q" | sed 's/;/; /g')" | tail -1); echo "$r: fired ($code)"
    [[ "$code" == 2* ]] || continue  # shortcut: a wake labelled between this fire and the clear is cleared unseen; rare, next owner tag or event re-adds it
    for n in $(grep -oE '^#[0-9]+' <<<"$q" | tr -d '#'); do gh api -X DELETE "repos/$repo/issues/$n/labels/wake-$r" >/dev/null 2>&1; done
  done
}

fire() { # <role> <reason>
  local trig secret token
  if batched "$1" && ! now_ok "$2"; then queue_add "$1" "$2"; return; fi
  trig=$(cfgq --arg r "$1" '.roles[$r].trigger // ""'); secret=$(cfgq --arg r "$1" '.roles[$r].secret // ""')
  [ -n "$secret" ] && token=${!secret:-}
  echo "waking $1: $2"
  if [ -z "$trig" ] || [ -z "$token" ]; then echo "::warning::$1 has no routine trigger or ${secret:-token} set; its schedule picks this up"; return 0; fi
  curl -fsS -X POST "https://api.anthropic.com/v1/claude_code/routines/$trig/fire" \
    -H "Authorization: Bearer $token" -H "anthropic-beta: experimental-cc-routine-2026-04-01" \
    -H "anthropic-version: 2023-06-01" -H "Content-Type: application/json" \
    -d "$(jq -n --arg t "wake-up: $2" '{text: $t}')" -o /dev/null -w '%{http_code}\n'
}

selftest() {
  local d fail=0; d=$(mktemp -d); trap 'rm -rf "$d"' RETURN
  pm='locksmith-walt[bot]'; lead='locksmith-linus[bot]'
  deb() { # <expected> <state> <labels-json> <comments as login|body ...>: opener is the PM
    local exp=$1 st=$2 lb=$3; shift 3
    local cs; cs=$(for x in "$@"; do jq -n --arg l "${x%%|*}" --arg b "${x#*|}" '{login: $l, body: $b}'; done | jq -s .)
    got=$(jq -n --arg s "$st" --argjson lb "$lb" --argjson cs "$cs" --arg o "${OPENER:-$pm}" \
      '{state: $s, labels: $lb, opener: $o, opener_body: "Stance: counter\nship X by Friday", comments: $cs}' | decide)
    [ "$got" = "$exp" ] && echo "ok: $exp" || { echo "FAIL: want '$exp' got '$got'"; fail=1; }
  }
  deb "wake lead turn 1 of 3" open '["debate"]'
  deb "wake pm turn 2 of 3" open '["debate"]' "$lead|Stance: counter"
  deb "wake pm turn 2 of 3" open '["debate"]' "$lead|Stance: counter" "$lead|one more thing"  # no double turns
  deb "wait lead settles it" open '["debate"]' "$lead|x" "$pm|x" "$lead|x" "$pm|x" "$lead|x"  # lead's last turn: it escalates itself
  deb "wait lead settles it" open '["debate"]' "$lead|x" "$pm|x" "$lead|x" "$pm|x" "$lead|x" "$pm|x"  # a 4th PM post is ignored
  OPENER=$lead deb "wake lead turn cap 3 reached: escalate to the owner" open '["debate"]' "$pm|x" "$lead|x" "$pm|x" "$lead|x" "$pm|x"
  deb "wake lead turn 3 of 3, the last" open '["debate"]' "$lead|x" "$pm|x" "$lead|x" "$pm|x"
  deb "wait lead settles it" open '["debate"]' "$lead|x" "$pm|Stance: agree" "$lead|recorded in #5"  # no fake turn after agree
  deb "wait lead settles it" open '["debate"]' "$lead|x" "$pm|x" "$lead|x" "$pm|x" "$lead|x" "$pm|x" "$lead|escalating"
  # identities paused: everyone posts as the owner; the role marker decides, an unmarked post is the owner
  deb "wake pm turn 2 of 3" open '["debate"]' "tomer555|<!-- agent -->
<!-- role: lead -->
Stance: counter"
  deb "wake lead turn 1 of 3" open '["debate"]' "tomer555|<!-- agent -->
no role marker"
  deb "wake lead pm agreed: record it and close" open '["debate"]' "$lead|Stance: counter" "$pm|stance: AGREE"
  deb "wake lead pm agreed to disagree: escalate to the owner" open '["debate"]' "$lead|x" "$pm|Stance: hold"
  deb "wait lead settles it" open '["debate"]' "$lead|Stance: hold"
  deb "wait with the owner" open '["debate","needs-owner"]' "$lead|Stance: hold"
  deb "wait closed" closed '["debate"]' "$lead|Stance: agree"
  deb "wake lead turn 1 of 3" open '["debate"]' "locksmith-alfie[bot]|Stance: agree"  # other roles are ignored
  deb "wake lead owner commented" open '["debate"]' "$lead|x" "tomer555|do the small version"

  ev() { # <expected> <event-name> <event-json>
    printf '%s' "$3" >"$d/ev.json"
    got=$(GITHUB_EVENT_NAME=$2 event "$d/ev.json")
    [ "$got" = "$(printf '%b' "$1")" ] && echo "ok: $2 -> ${1:-nothing}" || { echo "FAIL: $2 want '$1' got '$got'"; fail=1; }
  }
  ev 'lead\tneeds-rescue #5 opened' issues '{"action":"labeled","label":{"name":"needs-rescue"},"issue":{"number":5,"labels":[{"name":"needs-rescue"}]}}'
  ev '' issues '{"action":"labeled","label":{"name":"needs-owner"},"issue":{"number":5,"labels":[{"name":"needs-owner"}]}}'
  ev 'worker-b\tneeds-rescue #5 closed' issues '{"action":"closed","issue":{"number":5,"user":{"login":"locksmith-josie[bot]"},"labels":[{"name":"needs-rescue"},{"name":"needs-owner"}]}}'
  ev 'lead\towner replied on needs-owner #7' issue_comment '{"issue":{"number":7,"labels":[{"name":"needs-owner"}]},"comment":{"user":{"login":"tomer555"},"body":"approved"}}'
  ev '' issue_comment '{"issue":{"number":7,"labels":[{"name":"needs-owner"}]},"comment":{"user":{"login":"tomer555"},"body":"<!-- agent -->\nplan"}}'
  printf '%s' '[{"id":1,"user":{"login":"tomer555"},"body":"C","created_at":"2026-11-19T16:43:10Z"},{"id":2,"user":{"login":"tomer555"},"body":"<!-- agent -->\nx","created_at":"2026-11-19T16:43:20Z"}]' >"$d/c.json"
  r7='{"issue":{"number":7,"labels":[{"name":"needs-owner"}]},"comment":{"id":3,"user":{"login":"tomer555"},"body":"Approved C","created_at":"'
  COMMENTS_JSON=$d/c.json ev '' issue_comment "${r7}2026-11-19T16:43:23Z\"}}"  # 13 s after "C": that wake covers it
  COMMENTS_JSON=$d/c.json ev 'lead\towner replied on needs-owner #7' issue_comment "${r7}2026-11-19T16:45:00Z\"}}"
  COMMENTS_JSON=$d/c.json ev 'lead\towner replied on needs-owner #7' issue_comment '{"issue":{"number":7,"labels":[{"name":"needs-owner"}]},"comment":{"id":1,"user":{"login":"tomer555"},"body":"C","created_at":"2026-11-19T16:43:10Z"}}'
  ev '' issue_comment '{"issue":{"number":7,"labels":[{"name":"needs-owner"}],"pull_request":{}},"comment":{"user":{"login":"tomer555"},"body":"ok"}}'
  # owner tags: on issues and PRs, any label; several roles; the tag replaces the reply rule; agents and others cannot tag
  ev 'pm\towner tagged you on #7: u\nresearch\towner tagged you on #7: u' issue_comment '{"issue":{"number":7,"labels":[{"name":"needs-owner"}]},"comment":{"html_url":"u","user":{"login":"tomer555"},"body":"@locksmith-pm and @locksmith-research: check this"}}'
  ev 'worker-a\towner tagged you on #8: u' issue_comment '{"issue":{"number":8,"labels":[],"pull_request":{}},"comment":{"html_url":"u","user":{"login":"tomer555"},"body":"@locksmith-worker rebase please"}}'
  ev 'worker-c\towner tagged you on #8: u' issue_comment '{"issue":{"number":8,"labels":[],"pull_request":{}},"comment":{"html_url":"u","user":{"login":"tomer555"},"body":"@locksmith-harriet rebase please"}}'
  ev 'worker-b\towner tagged you on #8: u\nlead\towner tagged you on #8: u' issue_comment '{"issue":{"number":8,"labels":[],"pull_request":{}},"comment":{"html_url":"u","user":{"login":"tomer555"},"body":"@locksmith-hq/lead and @locksmith-hq/josie: look"}}'
  ev '' issue_comment '{"issue":{"number":8,"labels":[]},"comment":{"user":{"login":"tomer555"},"body":"<!-- agent -->\n@locksmith-lead"}}'
  ev '' issue_comment '{"issue":{"number":8,"labels":[]},"comment":{"user":{"login":"stranger"},"body":"@locksmith-lead"}}'
  ev '' issue_comment '{"issue":{"number":8,"labels":[]},"comment":{"user":{"login":"tomer555"},"body":"@locksmith-nobody"}}'
  # research (Ada) informs: her comment's tags wake those roles, never herself; other bots cannot tag
  ev 'worker-b\tresearch tagged you on #6: u\npm\tresearch tagged you on #6: u' issue_comment '{"issue":{"number":6,"labels":[{"name":"needs-research"}]},"comment":{"html_url":"u","user":{"login":"locksmith-ada[bot]"},"body":"Answer: yes.\n@locksmith-pm @locksmith-josie @locksmith-ada"}}'
  ev '' issue_comment '{"issue":{"number":6,"labels":[{"name":"needs-owner"}]},"comment":{"user":{"login":"locksmith-ada[bot]"},"body":"no tags"}}'
  ev '' issue_comment '{"issue":{"number":8,"labels":[]},"comment":{"user":{"login":"locksmith-alfie[bot]"},"body":"@locksmith-lead"}}'
  ev 'research\towner tagged you on #9: u' issue_comment '{"issue":{"number":9,"labels":[]},"comment":{"html_url":"u","user":{"login":"tomer555"},"body":"@locksmith-ada what does X cost?"}}'
  # no tag: the role that raised the issue gets the reply, else the lead
  ev 'pm\towner replied on needs-owner #7' issue_comment '{"issue":{"number":7,"body":"x\n<!-- raised-by: pm -->","labels":[{"name":"needs-owner"}]},"comment":{"user":{"login":"tomer555"},"body":"yes"}}'
  ev 'research\tneeds-research #6 opened' issues '{"action":"labeled","label":{"name":"needs-research"},"issue":{"number":6,"labels":[{"name":"needs-research"}]}}'
  ev 'pm\tneeds-work #16 opened' issues '{"action":"labeled","label":{"name":"needs-work"},"issue":{"number":16,"labels":[{"name":"needs-work"}]}}'
  ev 'worker-c\tneeds-work #16 closed' issues '{"action":"closed","issue":{"number":16,"body":"<!-- raised-by: worker-c -->","labels":[{"name":"needs-work"}]}}'
  ev 'worker-a\tneeds-rescue #5 closed' issues '{"action":"closed","issue":{"number":5,"body":"<!-- raised-by: worker -->","user":{"login":"locksmith-alfie[bot]"},"labels":[{"name":"needs-rescue"}]}}'
  ev 'lead\towner replied on needs-owner #7' issue_comment '{"issue":{"number":7,"body":"<!-- raised-by: optimizer -->","user":{"login":"tomer555"},"labels":[{"name":"needs-owner"}]},"comment":{"user":{"login":"tomer555"},"body":"done"}}'
  ev 'pm\tneeds-research #6 closed' issues '{"action":"closed","issue":{"number":6,"body":"<!-- raised-by: pm -->","labels":[{"name":"needs-research"}]}}'
  ev 'lead\tCI failed on main' workflow_run '{"workflow_run":{"name":"ci","conclusion":"failure","head_branch":"main","event":"push","pull_requests":[]}}'
  ev '' workflow_run '{"workflow_run":{"name":"ci","conclusion":"failure","head_branch":"feature","event":"pull_request","pull_requests":[]}}'
  # each worker owns its PRs: CI failures and failed merge reviews wake the PR's author (a PASS needs no one); owner PRs go to default_worker
  PR_AUTHOR='locksmith-josie[bot]' ev 'worker-b\tCI failed on PR #12 (claude/change-x)' workflow_run '{"workflow_run":{"name":"ci","conclusion":"failure","head_branch":"claude/change-x","event":"pull_request","pull_requests":[{"number":12}]}}'
