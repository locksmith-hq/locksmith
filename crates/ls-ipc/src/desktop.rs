//! Result types of the desktop app's commands (M14): what the webview receives. Like
//! [`crate::Response`], none of them carries a secret value (design D1).
//! TypeScript copies live in `packages/api-types` (`npm run export -w @locksmith/api-types`).

use crate::{ErrorCode, LeaseInfo};
use serde::Serialize;

#[derive(Serialize, Debug, Clone, PartialEq)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS))]
pub struct StatusView {
    pub locked: bool,
    pub leases: Vec<LeaseInfo>,
}

#[derive(Serialize, Debug, Clone, PartialEq)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS))]
pub struct AuditVerifyView {
    pub events: u64,
    /// First broken sequence number, if any.
    pub broken_at: Option<u64>,
    pub detail: String,
}

/// Relay ports (`null` when that relay is unavailable) and the explicit-proxy CA hosts.
#[derive(Serialize, Debug, Clone, PartialEq, Default)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS))]
pub struct RelayInfo {
    pub git_port: Option<u16>,
    pub http_port: Option<u16>,
    pub aws_port: Option<u16>,
    pub ca_hosts: Vec<String>,
}

/// Outcome of a native secure prompt: the only thing the webview learns about the value.
#[derive(Serialize, Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS))]
#[serde(rename_all = "lowercase")]
pub enum SecureOutcome {
    Submitted,
    Cancelled,
}

/// Daemon error codes plus the client-side ones.
#[derive(Serialize, Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS))]
pub enum CommandErrorCode {
    Locked,
    Denied,
    NotFound,
    BadRequest,
    Version,
    Internal,
    /// The daemon is not running or the socket is unreachable.
    Unavailable,
    /// The daemon answered with a response this command does not expect.
    Unexpected,
}

impl From<ErrorCode> for CommandErrorCode {
    fn from(c: ErrorCode) -> Self {
        match c {
            ErrorCode::Locked => Self::Locked,
            ErrorCode::Denied => Self::Denied,
            ErrorCode::NotFound => Self::NotFound,
            ErrorCode::BadRequest => Self::BadRequest,
            ErrorCode::Version => Self::Version,
            ErrorCode::Internal => Self::Internal,
        }
    }
}

/// The rejection value of every desktop command.
#[derive(Serialize, Debug, Clone, PartialEq)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS))]
pub struct CommandError {
    pub code: CommandErrorCode,
    pub message: String,
}

/// `cargo test -p ls-ipc --features ts export_bindings` regenerates `packages/api-types/src`.
#[cfg(all(test, feature = "ts"))]
mod export {
    use super::*;
    use crate::{AuditEvent, HttpTokenInfo, SelfReport, SessionSource, SourceKind, StartedBy};
    use ts_rs::{Config, TS};

    #[test]
    fn export_bindings() {
        let dir =
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/api-types/src");
        // serde_json writes i64/u64 as plain numbers; all our values fit in 2^53.
        let cfg = Config::new().with_large_int("number").with_out_dir(&dir);
        let mut index = String::from("// Generated by ts-rs from crates/ls-ipc; do not edit.\n");
        macro_rules! export {
            ($($t:ty),*) => {$(
                <$t>::export_all(&cfg).unwrap();
                let n = <$t>::ident(&cfg);
                index.push_str(&format!("export type {{ {n} }} from \"./{n}\";\n"));
            )*};
        }
        export!(
            LeaseInfo,
            StartedBy,
            SessionSource,
            SourceKind,
            SelfReport,
            AuditEvent,
            HttpTokenInfo,
            StatusView,
            AuditVerifyView,
            RelayInfo,
            SecureOutcome,
            CommandError,
            CommandErrorCode
        );
        std::fs::write(dir.join("index.ts"), index).unwrap();
    }
}
