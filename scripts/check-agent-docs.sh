#!/usr/bin/env bash
# Keeps agent guidance small (owner-only). Long instructions cost tokens on every run and get
# followed less; guidance belongs in skills (loaded on demand) and scripts (enforced).
# Limits in words. Fails CI when exceeded.
set -uo pipefail
fail=0
check() { # <file> <max-words>
  [ -f "$1" ] || return 0
  w=$(wc -w <"$1" | tr -d ' ')
  if [ "$w" -gt "$2" ]; then echo "agent-docs: $1 has $w words (max $2)"; fail=1; fi
}
check docs/agents/common.md 600
for f in docs/agents/{worker,review,health,research,merge}.md; do check "$f" 400; done
check docs/agents/lead.md 420  # owner 2026-11-18: owner-demand step
for f in .claude/skills/*/SKILL.md; do
  case "$f" in .claude/skills/openspec-*) continue ;; esac  # generated by the openspec CLI
  check "$f" 500
done
# Active lessons: at most 5 entries
n=$(grep -c '^## L[0-9]' docs/agents/lessons.md 2>/dev/null); n=${n:-0}
[ "$n" -le 5 ] || { echo "agent-docs: lessons.md has $n active lessons (max 5); retire into a skill or script"; fail=1; }
[ "$fail" -eq 0 ] && echo "agent-docs: OK"
exit "$fail"
