#!/usr/bin/env bash
# Owner replies waiting on open needs-owner issues (owner-only). Prints "<issue>\t<kind>" per issue whose
# latest comment is the owner's own (not agent-written). kind: approval (worker applies it) or demand
# (anything else: the lead discusses it on the issue until the owner approves a plan).
# `owner-replies.sh -` classifies one comment body from stdin and prints only the kind.
set -uo pipefail
repo=locksmith-hq/locksmith
owner="${OWNER_LOGIN:-tomer555}"

kind() { # <body>
  local b
  b=$(tr '[:upper:]' '[:lower:]' <<<"$1" | tr -s '[:space:]' ' ' | sed -E 's/^ +| +$//g; s/[.!]+$//')
  if grep -qxE 'approved?|yes|y|ok|okay|lgtm|go|go ahead|do it|ship it|agreed?|👍' <<<"$b"; then echo approval; else echo demand; fi
}

if [ "${1:-}" = - ]; then kind "$(cat)"; exit 0; fi

for i in $(gh api "repos/$repo/issues?labels=needs-owner&state=open" -q '.[].number'); do
  last=$(gh api "repos/$repo/issues/$i/comments?per_page=100" -q '[.[]]|last|select(.!=null)|[.user.login, .body]|@json')
  [ -n "$last" ] || continue
  who=$(jq -r '.[0]' <<<"$last"); body=$(jq -r '.[1]' <<<"$last")
  if [ "$who" = "$owner" ] && ! grep -qE '<!-- agent -->|Generated by \[Claude Code\]|run-metadata' <<<"$body"; then
    printf '%s\t%s\n' "$i" "$(kind "$body")"
  fi
done
